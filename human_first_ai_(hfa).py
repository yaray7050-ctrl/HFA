def final_evaluation(record, fairness_status):

    findings = []

    if record["risk_level"] in ["HIGH", "CRITICAL"]:
        findings.append("High priority risk review required.")

    if record["risk_level"] == "MEDIUM":
        findings.append("Additional monitoring recommended.")

    if fairness_status == "HIGH OBSERVED DIFFERENCE":
        findings.append("Fairness investigation recommended.")

    if not findings:
        findings.append(
            "No major issue identified by current tests."
        )

    return findings


