# PART 7: HFA DATABASE MANAGEMENT (SQLite)

import sqlite3

# Connect to database
connection = sqlite3.connect("hfa_database.db")

# Enable foreign keys
connection.execute("PRAGMA foreign_keys = ON")

cursor = connection.cursor()

# Table 1: AI Systems Cases
cursor.execute("""
CREATE TABLE IF NOT EXISTS cases (
    case_id INTEGER PRIMARY KEY,
    system_name TEXT,
    compliance_status TEXT,
    risk_score INTEGER,
    risk_level TEXT,
    governance_decision TEXT,
    alerts TEXT,
    recommendations TEXT,
    created_at TEXT
)
""")

# Table 2: Detected Violations
cursor.execute("""
CREATE TABLE IF NOT EXISTS violations (
    violation_id INTEGER PRIMARY KEY AUTOINCREMENT,
    case_id INTEGER,
    violation_type TEXT,
    severity TEXT,
    recommendation TEXT,
    FOREIGN KEY (case_id)
    REFERENCES cases(case_id)
)
""")

# Save HFA results into database
for _, row in df.iterrows():

    cursor.execute("""
    INSERT OR REPLACE INTO cases
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        int(row["case_id"]),
        row["system"],
        row["compliance_status"],
        int(row["risk_score"]),
        row["risk_level"],
        row["governance_decision"],
        json.dumps(row["alerts"], ensure_ascii=False),
        json.dumps(row["recommendations"], ensure_ascii=False),
        datetime.now().isoformat()
    ))

    # Refresh violations for this case
    cursor.execute(
        "DELETE FROM violations WHERE case_id = ?",
        (int(row["case_id"]),)
    )

    for violation in row["violations"]:

        rule = violation_rules[violation]

        cursor.execute("""
        INSERT INTO violations
        (case_id, violation_type, severity, recommendation)
        VALUES (?, ?, ?, ?)
        """, (
            int(row["case_id"]),
            rule["name"],
            rule["severity"],
            rule["recommendation"]
        ))

connection.commit()

print("HFA database created successfully.")
print("Cases and violations saved.")

